export async function seedTenSamplesPerCategory(): Promise<void> {
  const dbRes = await pool.query('SELECT current_database()');
  const currentDb = dbRes.rows[0]?.current_database;
  if (!currentDb || currentDb === 'homehub_production' || currentDb.includes('prod')) {
    throw new Error(`CRITICAL SAFETY ABORT: Refusing to seed test data into production DB (${currentDb})!`);
  }
  console.log(`[Demo Seed] Verified safe target database: ${currentDb}`);

  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    // 1. Ensure Verified Owner User exists
    await client.query(
      `INSERT INTO users (id, first_name, last_name, email, roles, is_active)
       VALUES ($1, 'HomeHub Demo', 'Owner Verified', $2, $3, true)
       ON CONFLICT (id) DO UPDATE SET roles = $3, is_active = true`,
      [OWNER_USER_ID, OWNER_EMAIL, JSON.stringify(['PROPERTY_OWNER'])]
    );

    let insertedCount = 0;

    for (const s of SAMPLES) {
      const propId = `demo-sample-${s.category.toLowerCase()}-${String(s.index).padStart(2, '0')}`;
      const ownId = `demo-own-${s.category.toLowerCase()}-${String(s.index).padStart(2, '0')}`;
      const listId = `demo-list-${s.category.toLowerCase()}-${String(s.index).padStart(2, '0')}`;

      const addressJson = {
        city: s.city,
        neighborhood: s.neighborhood,
        neighborhoodKu: s.neighborhoodKu,
        street: s.street,
        bedrooms: s.bedrooms,
        bathrooms: s.bathrooms,
        photos: [s.photoUrl],
        amenities: s.amenities,
      };

      // 1. Insert or update property
      await client.query(
        `INSERT INTO properties (
          id, name, type, address, square_feet, status, verification_status, management_preference, operating_model
        ) VALUES ($1, $2, $3, $4, $5, 'ACTIVE', 'VERIFIED', 'SELF_MANAGED', 'FULLY_MANAGED')
        ON CONFLICT (id) DO UPDATE SET
          name = EXCLUDED.name,
          type = EXCLUDED.type,
          address = EXCLUDED.address,
          square_feet = EXCLUDED.square_feet,
          status = 'ACTIVE',
          verification_status = 'VERIFIED'`,
        [propId, s.name, s.category, JSON.stringify(addressJson), s.squareFeet]
      );

      // 2. Insert or update ownership record (VERIFIED 100%)
      await client.query(
        `INSERT INTO ownership_records (
          id, property_id, owner_id, ownership_percentage, status
        ) VALUES ($1, $2, $3, 100, 'VERIFIED')
        ON CONFLICT (id) DO UPDATE SET
          ownership_percentage = 100,
          status = 'VERIFIED'`,
        [ownId, propId, OWNER_USER_ID]
      );

      // 3. Insert or update published rental listing (strictly FOR_RENT)
      await client.query(
        `INSERT INTO listings (
          id, property_id, publisher_user_id, type, price, currency, status, title, description
        ) VALUES ($1, $2, $3, 'FOR_RENT', $4, 'USD', 'PUBLISHED', $5, $6)
        ON CONFLICT (id) DO UPDATE SET
          type = 'FOR_RENT',
          price = EXCLUDED.price,
          currency = 'USD',
          status = 'PUBLISHED',
          title = EXCLUDED.title,
          description = EXCLUDED.description`,
        [listId, propId, OWNER_USER_ID, s.priceUsd, s.titleKu, s.descriptionKu]
      );

      insertedCount++;
    }

    await client.query('COMMIT');
    console.log(`[Demo Seed] Successfully seeded ${insertedCount} properties across all 9 categories (10 per category)!`);
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('[Demo Seed Error]:', err);
    throw err;
  } finally {
    client.release();
  }
}

// Direct execution
if (process.argv[1]?.endsWith('seed-10-samples-per-category.ts')) {
  seedTenSamplesPerCategory()
    .then(async () => {
      // Print counts breakdown
      const res = await pool.query(`
        SELECT p.type, count(*) as count
        FROM properties p
        JOIN listings l ON p.id = l.property_id
        WHERE l.status = 'PUBLISHED' AND l.type = 'FOR_RENT'
        GROUP BY p.type
        ORDER BY p.type;
      `);
      console.log('\nVerified Published Rental Listings Count by Property Type:');
      console.table(res.rows);

      // Count demo samples specifically
      const demoRes = await pool.query(`
        SELECT p.type, count(*) as demo_samples_count
        FROM properties p
        JOIN listings l ON p.id = l.property_id
        WHERE p.id LIKE 'demo-sample-%' AND l.status = 'PUBLISHED'
        GROUP BY p.type
        ORDER BY p.type;
      `);
      console.log('\nDedicated Demo Samples (demo-sample-*) Count per Category:');
      console.table(demoRes.rows);

      await pool.end();
      process.exit(0);
    })
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}

